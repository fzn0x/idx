/// Mean elements at `t` centuries: L', D, M, M', F and the eccentricity factor E.
fn arguments(t: f64) -> (f64, f64, f64, f64, f64, f64) {
    let lp = 218.3164477 + 481267.88123421 * t - 0.0015786 * t * t + t.powi(3) / 538841.0
        - t.powi(4) / 65194000.0;
    let d = 297.8501921 + 445267.1114034 * t - 0.0018819 * t * t + t.powi(3) / 545868.0
        - t.powi(4) / 113065000.0;
    let m = 357.5291092 + 35999.0502909 * t - 0.0001536 * t * t + t.powi(3) / 24490000.0;
    let mp = 134.9633964 + 477198.8675055 * t + 0.0087414 * t * t + t.powi(3) / 69699.0
        - t.powi(4) / 14712000.0;
    let f = 93.2720950 + 483202.0175233 * t - 0.0036539 * t * t - t.powi(3) / 3526000.0
        + t.powi(4) / 863310000.0;
    let e = 1.0 - 0.002516 * t - 0.0000074 * t * t;
    (lp, d, m, mp, f, e)
}

fn e_factor(m: i32, e: f64) -> f64 {
    match m {
        0 => 1.0,
        1 | -1 => e,
        _ => e * e,
    }
}

/// Apparent geocentric ecliptic-of-date longitude and latitude (degrees) and
/// distance (km) at `jde`.
pub fn apparent(jde: f64) -> Pos {
    let t = centuries(jde);
    let (lp, d, m, mp, f, e) = arguments(t);
    let (mut sl, mut sr, mut sb) = (0.0, 0.0, 0.0);
    for r in &LR {
        let arg = r[0] as f64 * d + r[1] as f64 * m + r[2] as f64 * mp + r[3] as f64 * f;
        let ef = e_factor(r[1], e);
        sl += r[4] as f64 * ef * sind(arg);
        sr += r[5] as f64 * ef * super::ephem::cosd(arg);
    }
    for r in &B {
        let ef = e_factor(r[1], e);
        sb += r[4] as f64
            * ef
            * sind(r[0] as f64 * d + r[1] as f64 * m + r[2] as f64 * mp + r[3] as f64 * f);
    }
    let (a1, a2, a3) = (
        119.75 + 131.849 * t,
        53.09 + 479264.290 * t,
        313.45 + 481266.484 * t,
    );
    sl += 3958.0 * sind(a1) + 1962.0 * sind(lp - f) + 318.0 * sind(a2);
    sb += -2235.0 * sind(lp)
        + 382.0 * sind(a3)
        + 175.0 * sind(a1 - f)
        + 175.0 * sind(a1 + f)
        + 127.0 * sind(lp - mp)
        - 115.0 * sind(lp + mp);
    Pos {
        lon: norm360(lp + sl / 1e6 + nutation_lon(t)),
        lat: sb / 1e6,
        dist: 385000.56 + sr / 1000.0,
    }
}

/// The apparent longitude alone (the backtest's fast path; same numbers).
pub fn longitude(jde: f64) -> f64 {
    let t = centuries(jde);
    let (lp, d, m, mp, f, e) = arguments(t);
    let mut sl = 0.0;
    for r in &LR[..59] {
        let arg = r[0] as f64 * d + r[1] as f64 * m + r[2] as f64 * mp + r[3] as f64 * f;
        sl += r[4] as f64 * e_factor(r[1], e) * sind(arg);
    }
    sl += 3958.0 * sind(119.75 + 131.849 * t)
        + 1962.0 * sind(lp - f)
        + 318.0 * sind(53.09 + 479264.290 * t);
    norm360(lp + sl / 1e6 + nutation_lon(t))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn meeus_example_47a() {
        // 1992 April 12, 0h TD: λ = 133.162655°, β = -3.229126°, Δ = 368409.7 km
        // (apparent λ adds the nutation, +0.004610°).
        let p = apparent(2_448_724.5);
        assert!((p.lon - 133.167265).abs() < 0.0005, "{}", p.lon);
        assert!((p.lat + 3.229126).abs() < 0.0005, "{}", p.lat);
        assert!((p.dist - 368_409.7).abs() < 1.0, "{}", p.dist);
    }

    #[test]
    fn longitude_alone_is_the_same_number() {
        for k in 0..200 {
            let jde = 2_415_020.5 + k as f64 * 197.3;
            assert_eq!(longitude(jde), apparent(jde).lon);
        }
    }
}
